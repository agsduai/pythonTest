# ===== 第1042课：代码风格与最佳实践-f字符串与格式化规范 =====
# 知识点：
#   - f-string 是首选：`f"{变量}"` 比 + 拼接和 % 格式化都清晰
#   - 常用格式化微语法：:.2f 两位小数、:>10 右对齐、:, 千分位
#   - f"{变量=}" 调试输出变量名和值；!r 输出 repr 形式
#   - 拼接多个字符串用 join，别在循环里 +=（效率低且难读）

# 案例一：三种拼接方式对比 —— f-string 最清爽
name = "小张"
score = 92.5
print("1. 加号拼接：" + name + " 得了 " + str(score) + " 分")  # 要手动 str()
print("2. format：{} 得了 {} 分".format(name, score))  # 占位符不直观
print(f"3. f-string：{name} 得了 {score} 分")  # 推荐，变量直接嵌进去

# 案例二：数字格式化 —— 小数位、千分位、百分比
pi = 3.14159265
big_num = 1234567.891
print(f"两位小数：{pi:.2f}")            # 3.14
print(f"千分位：{big_num:,.2f}")        # 1,234,567.89
print(f"百分比：{0.856:.1%}")           # 85.6%（自动乘 100 加 %）

# 报表场景：金额统一保留两位
total = 4567.8
print(f"合计金额：￥{total:,.2f}")

# 案例三：对齐与填充 —— 打印表格
# 场景：打印对齐的成绩单，中文按宽度补空格
rows = [("小张", 92), ("小李", 88), ("王大壮", 75)]
print(f"{'姓名':<6}{'成绩':>6}")
for name, s in rows:
    print(f"{name:<6}{s:>6}")
# 右对齐补零：编号标准化
print(f"订单号：{7:>05}")  # 00007
for i in [1, 12, 123]:
    print(f"ORD-{i:05d}")

# 案例四：调试专用 —— 变量名=值 一次输出
price, count = 9.9, 3
print(f"{price=} {count=} {price * count=}")  # 连表达式都能直接显示
text = "hello"
print(f"{text=!r}")  # 带引号的 repr 形式

# 案例五：join 拼接列表 —— 循环 += 的替代品
goods = ["苹果", "牛奶", "面包"]
# 烂：result = ""; for g in goods: result += g + "、"
print(f"商品清单：{'、'.join(goods)}")
print(f"编号清单：{', '.join(f'NO.{i + 1}' for i, g in enumerate(goods))}")

