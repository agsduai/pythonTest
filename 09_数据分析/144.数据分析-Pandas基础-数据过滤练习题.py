# 知识点：
#   - 布尔索引：df[条件] 只保留条件为 True 的行
#   - 多条件组合：&（与）、|（或）、~（非），每个条件要用括号包起来
#   - isin()：判断列值是否在给定列表中
#   - between()：判断数值是否在区间内（默认包含两端）
#   - query()：用字符串表达式过滤；str.contains()/startswith() 过滤文本

import pandas as pd

df = pd.DataFrame({
    "订单号": ["A01", "A02", "A03", "B01", "B02", "B03"],
    "城市": ["北京", "上海", "北京", "广州", "上海", "深圳"],
    "金额": [120, 89, 150, 99, 210, 75],
    "状态": ["已完成", "已完成", "已取消", "已完成", "已完成", "已取消"],
})

print(df)

# 单条件：金额大于 100
print("\n金额大于 100 的订单：")
print(df[df["金额"] > 100])

# 多条件：城市是北京 且 金额大于等于 100
print("\n北京且金额 >= 100：")
print(df[(df["城市"] == "北京") & (df["金额"] >= 100)])

# 多条件：城市是北京 或 上海
print("\n北京或上海的订单：")
print(df[(df["城市"] == "北京") | (df["城市"] == "上海")])

# 取反：状态不是“已取消”
print("\n未取消的订单：")
print(df[~(df["状态"] == "已取消")])

# isin：城市在指定列表中
print("\n城市为北京或广州：")
print(df[df["城市"].isin(["北京", "广州"])])

# between：金额在 80 到 150 之间（含端点）
print("\n金额在 80~150 之间：")
print(df[df["金额"].between(80, 150)])

# query：用字符串表达式过滤
print("\nquery：金额 > 100 且状态为已完成：")
print(df.query("金额 > 100 and 状态 == '已完成'"))

# 文本过滤：订单号以 A 开头
print("\n订单号以 A 开头：")
print(df[df["订单号"].str.startswith("A")])

