# 知识点：
#   - 函数：把一段可以重复使用的代码封装起来，并起一个名字
#   - 内置函数：Python 自带、可以直接调用的函数，如 print、len、max
#   - 自定义函数：用 def 关键字自己定义，先定义后调用
#   - 函数的好处：代码复用、结构清晰、便于维护

# 内置函数演示：统计一段文字的长度
text = "Python 函数真有趣"
print("文字长度：", len(text))       # len 是内置函数，返回长度
print("较大值：", max(3, 8, 5))     # max 是内置函数，返回最大值

# 自定义函数：把打招呼的代码封装起来
def greet():
    print("你好，欢迎学习 Python 函数！")

# 调用函数：函数定义好之后不会自动执行，必须调用
greet()
greet()  # 复用同一段代码，避免重复书写

# 没有函数时，重复的代码要写很多遍；有了函数只需调用一次名字
# 函数名后面的小括号表示“调用”，括号里可以放参数（下一课详细学习）

