# 知识点：
#   - 使用 def 关键字定义函数，基本格式为 def 函数名():
#   - 函数体需要缩进，通常缩进 4 个空格
#   - 函数必须先定义、后调用，定义时函数体不会执行
#   - 函数名要符合标识符规则，建议使用小写字母和下划线

# 定义函数：打印欢迎信息
def welcome():
    print("=" * 30)
    print("欢迎学习 Python 函数定义")
    print("=" * 30)

# 调用函数：函数定义后不会自动执行，必须调用
welcome()

# 定义函数：打印乘法口诀中的一行
def show_row():
    for i in range(1, 10):
        print(f"3 x {i} = {3 * i}")

show_row()

# 函数体暂时为空时，可以用 pass 占位，后续再补充代码
def todo():
    pass

# 没有 return 的函数，调用后默认返回 None
result = todo()
print("todo() 的返回值：", result)

# 函数可以重复调用，每次调用都会重新执行函数体
welcome()

print("程序结束")

