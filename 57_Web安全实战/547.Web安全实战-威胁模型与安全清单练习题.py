# ===== 第547课：Web安全实战-威胁模型与安全清单 =====
# 知识点：
#   - 安全三要素 CIA：机密性、完整性、可用性
#   - 威胁建模：先问“保护什么、怕谁、怎么进来、后果多大”
#   - OWASP Top 10 常见风险：注入、失效认证、敏感数据泄露、XXE、
#     失效访问控制、配置错误、XSS、反序列化、已知组件漏洞、日志监控不足
#   - 纵深防御：不依赖单一措施（校验 + 编码 + 权限 + 监控）
#   - 最小权限：应用账号、数据库账号、API Token 都只给必需权限
#   - 安全不是“加个密码”，而是持续过程
# 依赖：无

print("== 威胁建模四问 ==")
for q in [
    "保护什么？（用户密码、支付信息、订单数据）",
    "怕谁？（外部攻击者、恶意内部人员、误操作）",
    "怎么进来？（登录口、上传、API、第三方依赖）",
    "后果多大？（数据泄露、资金损失、服务不可用）",
]:
    print("  -", q)

# ---- 风险矩阵 ----
def risk_level(likelihood: int, impact: int) -> str:
    """likelihood/impact 取 1~5。"""
    score = likelihood * impact
    if score >= 15:
        return "高"
    if score >= 8:
        return "中"
    return "低"


print("\n== 风险矩阵示例 ==")
risks = [
    ("SQL 注入", 4, 5),
    ("弱密码", 4, 4),
    ("XSS", 3, 4),
    ("CSRF", 2, 4),
    ("依赖漏洞", 3, 3),
    ("日志泄露密钥", 2, 5),
]
for name, l, i in risks:
    print(f"  {name:10s} 可能性{l} × 影响{i} → 风险 {risk_level(l, i)}")

# ---- OWASP Top 10（简化清单）----
print("\n== OWASP Top 10 速览 ==")
owasp = [
    ("A01 失效访问控制", "越权访问别人的订单/后台"),
    ("A02 加密失败", "明文存密码、HTTP 传敏感数据"),
    ("A03 注入", "SQL/命令/LDAP 注入"),
    ("A04 不安全设计", "业务逻辑漏洞（如无限领券）"),
    ("A05 安全配置错误", "默认口令、调试接口暴露"),
    ("A06 易受攻击组件", "过期依赖、未打补丁"),
    ("A07 认证失败", "弱密码、会话固定"),
    ("A08 数据完整性失败", "不安全反序列化、供应链"),
    ("A09 日志监控不足", "被攻击了不知道"),
    ("A10 SSRF", "让服务器去访问内网地址"),
]
for code, desc in owasp:
    print(f"  {code:24s} {desc}")

# ---- 纵深防御 ----
print("\n== 纵深防御 ==")
layers = [
    ("输入层", "长度/类型/白名单校验"),
    ("处理层", "参数化 SQL、命令白名单、禁用 eval"),
    ("输出层", "HTML 转义、CSP、正确 Content-Type"),
    ("认证层", "强密码哈希、MFA、会话安全"),
    ("权限层", "最小权限、每次请求校验归属"),
    ("运维层", "HTTPS、补丁、备份、日志告警"),
]
for name, desc in layers:
    print(f"  {name}: {desc}")

