# 课程来源：B站 BV1sHU9BmEne
# 知识点：
#   - 比较运算符：==、!=、>、<、>=、<=
#   - 比较的结果是布尔值 True 或 False
#   - = 是赋值，== 是比较，两者不要混淆
#   - 字符串也可以比较大小（按字符编码逐位比较）
#   - 支持链式比较

a = 10
b = 20

print(a == b)     # 判断相等
print(a != b)     # 判断不相等
print(a > b)      # 大于
print(a < b)      # 小于
print(a >= 10)    # 大于等于
print(a <= 9)     # 小于等于

# 比较的结果可以用变量保存
result = a < b
print(result)

# 数字和浮点数比较的是数值大小
print(10 == 10.0)
print(10 < 9.99)

# 字符串比较：按字符编码从左到右逐位比较
print("abc" == "abc")
print("abc" == "ABC")
print("apple" < "banana")

# 链式比较：等价于 a < b and b < 30
print(a < b < 30)

# = 是赋值，== 是比较
number = 10              # 赋值
print(number == 10)      # 比较

