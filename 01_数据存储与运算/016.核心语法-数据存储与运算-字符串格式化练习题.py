# 知识点：
#   - 字符串格式化：把变量按指定位置嵌入字符串
#   - f-string：f"..."，用 {变量} 占位（推荐）
#   - % 占位符：%s、%d、%f
#   - str.format()：用 {} 占位
#   - 数字格式化：保留小数位、百分比、千分位

name = "小明"
age = 18
score = 92.567
price = 12345.678

# 方式一：f-string，引号前加 f，{} 中可以直接写变量或表达式
print(f"我叫{name}，今年{age}岁")
print(f"明年我就{age + 1}岁了")
print(f"两数之和：{10 + 20}")

# 数字格式化：{值:.2f} 表示保留两位小数
print(f"成绩：{score:.2f} 分")
print(f"价格：{price:.2f} 元")

# 百分比：{值:.1%} 表示转成百分比并保留一位小数
rate = 0.856
print(f"正确率：{rate:.1%}")

# 千分位：{值:,} 用逗号分隔
print(f"金额：{price:,}")

# 方式二：% 占位符，%s 字符串、%d 整数、%f 浮点数
print("我叫%s，今年%d岁" % (name, age))
print("成绩：%.2f" % score)

# 方式三：str.format()，用 {} 占位
print("我叫{}，今年{}岁".format(name, age))
print("我叫{0}，今年{1}岁".format(name, age))
print("我叫{名字}，今年{年龄}岁".format(名字=name, 年龄=age))

# 注意：{} 的个数要和参数个数对应，否则会报错
# print("我叫{}，今年{}岁".format(name))

