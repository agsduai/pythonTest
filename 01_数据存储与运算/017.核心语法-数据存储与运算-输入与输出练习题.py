# 知识点：
#   - input()：从键盘读取输入，运行后按提示输入
#   - input() 的返回值永远是字符串
#   - 需要数字时用 int()、float() 转换
#   - print() 的 sep 和 end 参数
#   - 输出时可以用逗号分隔多个值

# input() 会在控制台等待输入，括号里的文字是提示语
# 运行后按提示输入姓名
name = input("请输入你的姓名：")
print("你好，" + name)

# input() 得到的内容永远是字符串，哪怕输入的是数字
# 运行后按提示输入年龄
age = input("请输入你的年龄：")
print(age + "岁")          # 这里 age 是字符串，可以拼接
# print(age + 1)           # 会报错：字符串不能和整数相加
age = int(age)             # 转成整数后才能做算术运算
print("明年你", age + 1, "岁")

# 输入小数：用 float() 转换
# 运行后按提示输入单价和数量
price = float(input("请输入商品单价："))
count = int(input("请输入购买数量："))
print("总价：", price * count)

# 一次输出多个值，默认用空格分隔
print("Python", "AI", "数据分析")

# sep 参数：指定多个值之间的分隔符
print("2026", "11", "12", sep="-")
print("A", "B", "C", sep=" | ")

# end 参数：指定输出结束后追加什么，默认是换行符 \n
print("正在加载", end="")
print("完成")
print("第一行", end="\n\n")
print("第二行")

