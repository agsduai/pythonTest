# 知识点：
#   - 算术运算符：+、-、*、/、//、%、**
#   - / 的结果一定是浮点数
#   - // 整除向下取整，% 取余
#   - ** 幂运算，优先级最高且从右往左结合
#   - 括号可以改变运算顺序

a = 17
b = 5

print("a + b =", a + b)
print("a - b =", a - b)
print("a * b =", a * b)
print("a / b =", a / b)      # 除法，结果是浮点数
print("a // b =", a // b)    # 整除，只保留整数部分
print("a % b =", a % b)      # 取余，17 ÷ 5 余 2
print("a ** b =", a ** b)    # 幂运算，17 的 5 次方

# 两个整数相除，结果也是浮点数
print(10 / 2)

# 整除和取余遇到负数时，结果按“向下取整”计算
print(-17 // 5)    # -4
print(-17 % 5)     # 3

# 运算符优先级：() > ** > * / // % > + -
print(2 + 3 * 4)
print((2 + 3) * 4)

# 幂运算从右往左计算
print(2 ** 3 ** 2)     # 等价于 2 ** 9
print((2 ** 3) ** 2)   # 等价于 8 ** 2

# 浮点数运算可能存在精度误差，这是计算机存储方式导致的
print(0.1 + 0.2)

# 常用小技巧：秒数换算成时、分、秒
total_seconds = 3661
print("小时：", total_seconds // 3600)
print("分钟：", total_seconds % 3600 // 60)
print("秒：", total_seconds % 60)

