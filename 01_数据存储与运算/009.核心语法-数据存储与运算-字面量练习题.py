# 知识点：
#   - 字面量：代码中直接写出来的固定值
#   - 常见字面量：整数、浮点数、字符串、布尔值、空值
#   - 科学计数法表示很大或很小的数
#   - 使用 print() 把字面量输出到控制台

# 整数（int）：不带小数点的数字，可以写正数、负数和 0
print(100)
print(-25)
print(0)

# 浮点数（float）：带小数点的数字
print(3.14)
print(-0.5)
print(2.0)

# 字符串（str）：用一对引号包裹的文字，单引号、双引号都可以
print("你好，Python")
print('hello world')

# 布尔值（bool）：只有 True 和 False 两个值，首字母必须大写
print(True)
print(False)

# 空值 None：表示“没有值”，首字母必须大写
print(None)

# 科学计数法：e 表示 10 的多少次方
print(1.5e3)    # 1.5 × 10³，结果是 1500.0
print(2e-3)     # 2 × 10⁻³，结果是 0.002

# 字面量也可以直接参与算术运算，运算结果仍然是字面量
print(10 + 20)
print(3.5 * 2)
print("Py" + "thon")

