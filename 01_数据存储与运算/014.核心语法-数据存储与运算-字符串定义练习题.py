# 知识点：
#   - 字符串：用引号包裹的一段文字
#   - 单引号、双引号、三引号的定义方式
#   - 引号嵌套：外层与内层引号要不同
#   - 转义字符：\n、\t、\\、\'、\"
#   - 三引号可以保留换行，也可以当作多行注释

# 单引号与双引号效果相同
s1 = 'Python'
s2 = "Python"
print(s1)
print(s2)

# 字符串里本身有单引号时，外层用双引号
s3 = "It's a good day"
print(s3)

# 字符串里本身有双引号时，外层用单引号
s4 = '老师问："今天作业写完了吗？"'
print(s4)

# 三引号可以换行书写，换行和空格都会保留
s5 = """第一行
第二行
第三行"""
print(s5)

# 三引号也常用来写多行注释
"""
这是多行注释的写法
解释器会忽略它
"""

# 转义字符
print("第一行\n第二行")        # \n 换行
print("姓名\t年龄")            # \t 制表符
print("C:\\Users\\test")      # \\ 输出一个反斜杠
print("她说：\"你好\"")        # \" 输出双引号
print('It\'s ok')              # \' 输出单引号

# 空字符串：两个引号中间什么都没有
empty = ""
print(empty)

