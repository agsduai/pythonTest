import numpy as np

# ---- 1. 造一份“身高 → 体重”的合成数据（y = 0.9x - 100 + 噪声）----
rng = np.random.default_rng(42)
height = rng.uniform(150, 190, size=50)          # 特征：身高
weight = 0.9 * height - 100 + rng.normal(0, 2.5, size=50)   # 标签：体重 + 噪声

print("X 形状：", height.shape, "| y 形状：", weight.shape)
print("前 5 条样本：")
for h, w in list(zip(height, weight))[:5]:
    print(f"  身高 {h:.1f} → 体重 {w:.1f}")

# ---- 2. 看特征与标签的相关性（线性回归的“可行性检查”）----
corr = np.corrcoef(height, weight)[0, 1]
print(f"\n相关系数 r = {corr:.3f}（越接近 1，线性关系越强）")
print(f"特征均值 {height.mean():.1f}，标签均值 {weight.mean():.1f}")

# ---- 3. 规范形状：sklearn 风格的二维 X ----
X = height.reshape(-1, 1)          # (50, 1)：50 个样本、1 个特征
y = weight.reshape(-1, 1)          # (50, 1)
print("规范后的形状：X", X.shape, "y", y.shape)

