# ===== 第523课：推荐系统进阶-概述与架构 =====
# 知识点：
#   - 推荐系统目标：从海量物品中挑出用户可能喜欢的少量内容
#   - 反馈类型：显式（评分/点赞）、隐式（点击/停留/购买）
#   - 经典两阶段：召回（候选生成，快而粗）→ 排序（精排，慢而准）
#   - 召回来源：热门、协同过滤、内容相似、向量检索
#   - 评估：离线（precision@k/NDCG）+ 在线（CTR/转化/留存 A/B）
#   - 与第42章协同过滤、第36章文本相似、第48章 A/B 的关系
#   - 本路线：内容推荐 → 矩阵分解 → 关联规则 → 评估 → 冷启动 → 混合 → 综合
# 依赖：无

# ---- 用户-物品评分矩阵（显式反馈）----
RATINGS = {
    "小明": {"Python": 5, "算法": 4, "前端": 2, "数据库": 4},
    "小红": {"Python": 4, "算法": 5, "前端": 2, "数据库": 3},
    "小刚": {"Python": 2, "前端": 5, "设计": 4, "数据库": 1},
    "小丽": {"前端": 4, "设计": 5, "数据库": 2},
    "小强": {"Python": 5, "算法": 5, "数据库": 4, "后端": 5},
}

users = list(RATINGS)
items = sorted({item for r in RATINGS.values() for item in r})
print("== 用户-物品矩阵 ==")
print("        " + "".join(f"{it:>6s}" for it in items))
for u in users:
    row = [str(RATINGS[u].get(it, "·")) for it in items]
    print(f"  {u:4s}  " + "".join(f"{v:>6s}" for v in row))

# ---- 稀疏度 ----
total_cells = len(users) * len(items)
filled = sum(len(r) for r in RATINGS.values())
print(f"\n矩阵大小 {total_cells}，有评分 {filled}，稀疏度 {1 - filled / total_cells:.1%}")
print("  真实系统稀疏度通常 > 99%，所以需要内容特征/隐式行为补充")

# ---- 两阶段架构 ----
print("\n== 两阶段架构 ==")
print("  召回（千级）：热门 + 协同过滤 + 内容相似 + 向量检索")
print("  排序（百级）：LR/GBDT/深度模型，融合用户/物品/上下文特征")
print("  重排：多样性、去重、业务规则、广告位")

print("\n== 离线 vs 在线评估 ==")
rows = [
    ("离线", "precision@k / recall@k / NDCG", "快、可复现", "和线上效果有偏差"),
    ("在线", "CTR / 转化率 / 留存 / GMV", "真实", "成本高、周期长"),
    ("A/B", "随机分流对比", "因果可信", "需要样本量与时间"),
]
print(f"  {'方式':<6}{'指标':<32}{'优点':<14}{'缺点'}")
for r in rows:
    print(f"  {r[0]:<6}{r[1]:<32}{r[2]:<14}{r[3]}")

# ---- 常见基线 ----
print("\n== 先做基线 ==")
for item in [
    "热门推荐：按销量/评分排序，简单但有效",
    "最近流行：时间衰减的热门",
    "基于内容：用户喜欢过的相似物品",
    "协同过滤：相似用户喜欢的物品",
    "基线能跑通流程、量化收益，再谈复杂模型",
]:
    print("  -", item)

