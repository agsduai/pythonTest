# 课程来源：B站 BV1sHU9BmEne
# 知识点：
#   - 提示词（Prompt）是用户发给大模型的指令，质量直接影响回答质量
#   - 结构化提示词通常包含：角色、任务、背景、输入、输出格式、限制条件
#   - 少样本提示（Few-shot）：给 1~3 个示例，让模型模仿格式和风格
#   - 使用分隔符（如 ---）把指令和待处理内容分开，避免混淆
#   - 需要推理时，可要求“先分析再给结论”；需要稳定输出时降低 temperature
#   - 提示词要反复测试和迭代，用同一组问题比较不同版本的效果
# 依赖：无（仅使用标准库）

def build_prompt(role, task, context, output_format):
    """按“角色 + 任务 + 背景 + 输出格式”组装结构化提示词。"""
    return (
        f"你是一位{role}。\n"
        f"任务：{task}\n"
        f"背景资料：\n---\n{context}\n---\n"
        f"输出要求：{output_format}\n"
        "如果资料不足，请明确说明，不要编造。"
    )


def few_shot_prompt(text):
    """用示例告诉模型期望的输出格式（情感分类）。"""
    return (
        "请判断下面评论的情感，只输出“正面”或“负面”。\n"
        "示例1：\n评论：课程讲得很清楚，收获很大。\n情感：正面\n"
        "示例2：\n评论：声音太小，听不清楚。\n情感：负面\n"
        f"现在判断：\n评论：{text}\n情感："
    )


if __name__ == "__main__":
    article = "Python 是一门通用编程语言，语法简洁，常用于数据分析、人工智能和 Web 开发。"
    prompt = build_prompt(
        role="Python 课程助教",
        task="把下面的内容总结成一句话，面向零基础学员。",
        context=article,
        output_format="一句话，不超过 40 个汉字，不使用专业术语。",
    )
    print("== 结构化提示词 ==")
    print(prompt)
    print("\n== 少样本提示词 ==")
    print(few_shot_prompt("这个功能很好用，帮我节省了很多时间。"))

