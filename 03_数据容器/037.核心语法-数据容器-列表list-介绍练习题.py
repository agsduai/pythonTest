# 知识点：
#   - 列表用 [] 定义，元素之间用英文逗号分隔
#   - 列表可以保存任意类型的数据，也支持嵌套
#   - 列表是有序的，可以通过下标访问，下标从 0 开始
#   - 支持负数下标，-1 表示最后一个元素
#   - 列表是可变的，可以直接修改指定下标的元素

# 定义列表：保存三个名字
names = ["小明", "小红", "小刚"]
print(names)

# 通过正数下标访问元素
print(names[0])
print(names[1], names[2])

# 通过负数下标访问元素
print(names[-1], names[-3])

# 列表可变：修改下标 1 对应的元素
names[1] = "小丽"
print(names)

# 列表可以保存不同类型的数据
scores = [90, 85.5, True, "缺考"]
print(scores)

# 嵌套列表：列表中的元素还是列表
matrix = [[1, 2], [3, 4], [5, 6]]
print(matrix)
print(matrix[1])
print(matrix[1][0])
print(len(matrix), len(matrix[0]))

# 使用 for 循环依次取出列表中的每个元素
for item in names:
    print(item)

