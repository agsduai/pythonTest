# 知识点：
#   - 组包：多个值用逗号连接会自动组成元组
#   - 解包：把元组中的元素依次赋值给多个变量
#   - 带星号的解包：*rest 收集剩余元素（得到列表）
#   - 解包时变量个数要与元素个数匹配（带 * 的变量除外）

# ---------- 示例代码 ----------
# 1. 组包：等号右边多个值，自动打包成元组
point = 10, 20
print(point)                       # (10, 20)，自动组包成元组

# 2. 基本解包：变量个数与元素个数一致
x, y = point                       # 把 10 赋给 x，20 赋给 y
print(x, y)                        # 10 20

# 3. 交换两个变量（本质是组包后再解包）
a, b = 1, 2
a, b = b, a
print(a, b)                        # 2 1

# 4. 带星号的解包：first 取第一个，rest 收集剩下的元素（列表）
scores = (90, 85, 77, 60)
first, *rest = scores
print(first, rest)                 # 90 [85, 77, 60]

*head, last = scores
print(head, last)                  # [90, 85, 77] 60

# 5. 星号放在中间也可以
one, *middle, end = scores
print(one, middle, end)            # 90 [85, 77] 60

# 6. 嵌套解包：内层也要用对应数量的变量接住
student = ("小明", (95, 88))
name, (chinese, math) = student
print(name, chinese, math)         # 小明 95 88

