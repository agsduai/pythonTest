# 知识点：
#   - 切片语法：列表[开始下标:结束下标:步长]
#   - 切片包含开始下标，不包含结束下标，即左闭右开
#   - 省略开始下标默认从 0 开始，省略结束下标默认取到末尾
#   - 步长可以是负数，表示从后向前取元素
#   - 切片得到一个新列表，不会修改原列表

numbers = [10, 20, 30, 40, 50, 60]

# 取下标 1 到 3 的元素，不包含下标 4
print(numbers[1:4])

# 省略开始下标：从开头取到下标 3 之前
print(numbers[:3])

# 省略结束下标：从下标 3 取到末尾
print(numbers[3:])

# 开始和结束都省略：复制整个列表
print(numbers[:])

# 步长为 2：每隔一个元素取一个
print(numbers[::2])

# 指定开始、结束和步长
print(numbers[1:5:2])

# 负数下标切片：取最后三个元素
print(numbers[-3:])

# 负数下标切片：从倒数第 4 个取到倒数第 2 个之前
print(numbers[-4:-1])

# 步长为 -1：把列表倒序
print(numbers[::-1])

# 步长为 -1 且指定范围：从下标 4 向前取到下标 2 之后
print(numbers[4:1:-1])

# 切片产生新列表，修改新列表不会影响原列表
part = numbers[1:3]
part[0] = 999
print(part)
print(numbers)

# 字符串也支持同样的切片语法
text = "abcdef"
print(text[1:4])
print(text[::-1])

