# ===== 第224课：正则表达式-零宽断言 =====
# 知识点：
#   - 零宽断言：只匹配“位置”，不消耗任何字符
#   - (?=...) 正向先行：右边必须是 ...
#   - (?!...) 负向先行：右边必须不是 ...
#   - (?<=...) 正向后行：左边必须是 ...
#   - (?<!...) 负向后行：左边必须不是 ...
#   - 经典应用：按上下文取值、密码强度校验

import re

# 正向先行：只要“元”前面的数字
print(re.findall(r"\d+(?=元)", "苹果 5元，香蕉 3斤，橙子 8元"))    # ['5', '8']

# 正向后行：只要“￥”后面的数字
print(re.findall(r"(?<=￥)\d+", "原价￥99，现价￥120"))            # ['99', '120']

# 负向先行：后面不是“元”的数字（加 (?!\d) 防止匹配到数字的一部分）
print(re.findall(r"\d+(?!元)(?!\d)", "苹果 5元，香蕉 3斤"))        # ['3']

# 负向后行：前面不是“-”的数字（排除负数）
print(re.findall(r"(?<!-)\d+", "温度 8 度到 -3 度"))               # ['8']

# 密码强度校验：8 位以上，且同时包含字母和数字
def check_password(pwd):
    return bool(re.search(r"^(?=.*[a-zA-Z])(?=.*\d).{8,}$", pwd))


print(check_password("abc12345"))    # True
print(check_password("12345678"))    # False：没有字母
print(check_password("abcdefg1"))    # True
print(check_password("short1"))      # False：不足 8 位

# 逗号千分位：给数字加逗号（从右往左每 3 位一断）
print(re.sub(r"(?<=\d)(?=(\d{3})+$)", ",", "12345678"))

