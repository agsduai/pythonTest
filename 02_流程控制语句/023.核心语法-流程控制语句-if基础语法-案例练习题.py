# 知识点：
#   - 把 if 语句应用到实际生活场景
#   - 多个 if 相互独立，各自判断，互不影响
#   - 条件中组合比较运算符与逻辑运算符
#   - 空字符串与布尔值在条件中的含义

# 案例一：判断是否达到上网年龄
age = 17
if age >= 18:
    print("已成年，可以进入网吧")
if age < 18:
    print("未成年，禁止进入网吧")  # 两个 if 都会判断，这里命中第二个

# 案例二：判断用户名是否为空
username = "小明"
if username != "":
    print(f"欢迎你，{username}")  # 非空字符串条件为 True

# 案例三：判断是否能领取新人礼包
is_new_user = True
money = 50
if is_new_user and money >= 0:
    print("符合新人礼包领取条件")

# 案例四：判断分数是否在合法范围内
score = 95
if score >= 0 and score <= 100:
    print("分数合法")

# 案例五：判断是否满足打折条件
vip = False
total = 260
if vip or total >= 200:
    print("可以享受优惠")  # 满足其中一个条件即可

