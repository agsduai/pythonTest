# 课程来源：B站 BV1sHU9BmEne
# 知识点：
#   - while True 实现“不知道要循环多少次”的游戏
#   - input() 接收输入，int() 转换成整数
#   - if/elif/else 根据大小关系给出提示
#   - break 在猜中时结束循环
#   - 用计数器统计猜测次数

print("欢迎来到猜数字游戏！")
print("系统已经预设了一个 1 到 100 之间的整数。")

target = 42  # 本示例不使用随机数，固定目标方便直接测试
count = 0

while True:
    guess = int(input("请输入你猜的数字（运行后按提示输入）："))  # 输入并转成整数
    count += 1
    if guess > target:
        print("猜大了，再试试！")
    elif guess < target:
        print("猜小了，再试试！")
    else:
        print(f"恭喜你，猜对了！答案就是 {target}")
        print(f"你一共猜了 {count} 次")
        break  # 猜中后立即结束循环

