# 知识点：
#   - if 语句的基本格式：if 条件:
#   - 冒号与缩进（通常 4 个空格）
#   - 用比较运算符构造判断条件
#   - 条件成立时才执行缩进代码块

# 示例一：判断年龄是否成年
age = 20
if age >= 18:
    print("已成年，可以独立办理业务")
    print(f"当前年龄：{age} 岁")  # 回顾 f-string 格式化

# 示例二：判断成绩是否及格
score = 85
if score >= 60:
    print("成绩及格")

# 示例三：条件不成立时，if 代码块不会执行
temperature = 30
if temperature > 35:
    print("高温预警")  # 30 不大于 35，这一行不会输出
print("判断结束")

# 示例四：用逻辑运算符组合条件
age = 22
has_ticket = True
if age >= 18 and has_ticket:
    print("可以入场观看演出")  # 两个条件都为 True 才执行

